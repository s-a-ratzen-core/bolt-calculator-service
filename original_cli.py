import math

# Плотность стали (кг/м^3)
p = 7850

print("Добро пожаловать в программу для расчёта объема и массы болта!")
print("Введите размеры болта в миллиметрах")

# Ввод данных о геометрических параметрах болта (в миллиметрах)
# Стержень
dk_mm = float(input("Диаметр стержня: "))
hk_mm = float(input("Длина стержня: "))
# Резьба
hr_mm = float(input("Длина резьбы: "))
sr_mm = float(input("Шаг резьбы: "))
# Головка
sh_mm = float(input("Размер под ключ (мм): "))
hh_mm = float(input("Высота головки hh (мм): "))


# Перевод в метры
# Стержень
dk = dk_mm * 0.001
hk = hk_mm * 0.001
# Резьба
hr = hr_mm * 0.001
sr = sr_mm * 0.001
# Головка
sh = sh_mm * 0.001
hh = hh_mm * 0.001

# Длина гладкой части
hs = hk - hr

# Расчётный диаметр резьбы
dr = dk - 0.65 * sr

# Объём стержня
Vk = math.pi * dk**2 / 4 * hs
# Объём резьбы
Vt = math.pi * dr**2 / 4 * hr
# Объём шестигранной головки
Vh = hh * math.sqrt(3) / 2 * sh**2
# Общий объём
Vg = Vk + Vt + Vh

# Масса болта
m = p * Vg

# Вывод результата
print("Результаты расчёта:")
print(f"Объём болта: {Vg:.6e} м³")
print(f"Масса болта: {m:.4f} кг")
